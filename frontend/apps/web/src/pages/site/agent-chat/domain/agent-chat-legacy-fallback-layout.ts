export function restoreLegacyFallbackLayout(content: string) {
  const text = content.trim().replace(/\s+/g, " ")
  if (!text) return ""

  if (text === LEGACY_MODEL_UNAVAILABLE) return structuredModelUnavailableFallback()
  if (text === LEGACY_MODEL_CONFIG_UNAVAILABLE) return structuredModelConfigFallback()
  if (text === LEGACY_NO_CONTENT) return structuredNoContentFallback()
  if (text === LEGACY_EXECUTION_GAP) return structuredExecutionGapFallback()
  if (text === LEGACY_ROUTING_FAILURE) return structuredRoutingFailureFallback()

  return ""
}

