function structuredAnswer(lines: string[]) {
  return lines
    .flatMap((line) => (line.startsWith("## ") ? ["", line, ""] : [line]))
    .join("\n")
    .replace(/^\n+/, "")
    .replace(/\n{3,}/g, "\n\n")
    .trim()
}

function cjk(...codes: number[]) {
  return String.fromCodePoint(...codes)
}
